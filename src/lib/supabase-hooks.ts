// ─── PROFILE HOOK ───────────────────────────────────────────────

export function useProfile(userId?: string) {
  const [profile, setProfile] = useState<any>(null);
  const [loading, setLoading] = useState(true);
  const [refreshCounter, setRefreshCounter] = useState(0);
  const { user } = useAuth();
  const profileId = userId ?? user?.id;

  useEffect(() => {
    if (!profileId) return;

    const fetchProfile = async () => {
      setLoading(true);

      // Try to get existing profile
      const { data, error } = await supabase
        .from("profiles")
        .select("*")
        .eq("id", profileId)
        .maybeSingle();

      if (data) {
        setProfile(data);
      } else {
        // Profile doesn't exist yet — create one
        const { data: sessionData } = await supabase.auth.getSession();
        if (sessionData?.session?.user) {
          const newProfile = {
            id: profileId,
            name: (sessionData.session.user.user_metadata as any)?.name
              || sessionData.session.user.email?.split("@")[0]
              || "User",
            email: sessionData.session.user.email || "",
            status: "offline" as const,
          };
          const { data: inserted } = await supabase
            .from("profiles")
            .insert(newProfile as any)
            .select()
            .single();

          if (inserted) {
            setProfile(inserted);
          } else {
            setProfile(null);
          }
        }
      }

      setLoading(false);
    };

    fetchProfile();
  }, [profileId, refreshCounter]);

  const updateProfile = async (updates: any) => {
    if (!profileId) return;
    await (supabase.from("profiles") as any).update(updates).eq("id", profileId);
    // Optimistic update
    setProfile((prev: any) => (prev ? { ...prev, ...updates } : prev));
  };

  const refresh = () => setRefreshCounter((c) => c + 1);

  return { profile, loading, updateProfile, refresh };
}
