// ─── NOTIFICATIONS HOOK ─────────────────────────────────────────

// The bell badge in Dashboard and the panel in NotificationsPanel are mounted
// at the same time, so notification state is shared through a tiny store.
// Previously each call site kept its own copy, which meant marking something as
// read in the panel left the badge showing a stale count.
type NotificationListener = (list: any[]) => void;
const notificationListeners = new Set<NotificationListener>();
let notificationCache: any[] = [];
let notificationUserId: string | null = null;
let notificationChannel: any = null;
let notificationStarted = false;

function publishNotifications(list: any[]) {
  notificationCache = list;
  notificationListeners.forEach((fn) => fn(list));
}

export function useNotifications() {
  const [notifications, setNotifications] = useState<any[]>(notificationCache);
  const [loading, setLoading] = useState(notificationStarted);
  const [userId, setUserId] = useState<string | null>(notificationUserId);

  useEffect(() => {
    const listener: NotificationListener = (list) => setNotifications(list);
    notificationListeners.add(listener);
    return () => {
      notificationListeners.delete(listener);
    };
  }, []);

  useEffect(() => {
    supabase.auth.getSession().then(({ data }) => {
      setUserId(data.session?.user?.id ?? null);
    });
  }, []);

  useEffect(() => {
    if (!userId) return;
    notificationUserId = userId;

    const start = async () => {
      const { data } = await supabase
        .from("notifications")
        .select("*")
        .eq("user_id", userId)
        .order("created_at", { ascending: false })
        .limit(20);

      publishNotifications(data ?? []);
      setLoading(false);
      notificationStarted = true;
    };

    if (!notificationStarted) {
      start();
      notificationChannel = supabase
        .channel(`notifications:${userId}`)
        .on(
          "postgres_changes",
          { event: "INSERT", schema: "public", table: "notifications", filter: `user_id=eq.${userId}` },
          (payload) => {
            const newNotif: any = payload.new;
            publishNotifications([newNotif, ...notificationCache]);
          }
        )
        .on(
          "postgres_changes",
          { event: "UPDATE", schema: "public", table: "notifications", filter: `user_id=eq.${userId}` },
          (payload) => {
            const updated: any = payload.new;
            publishNotifications(
              notificationCache.map((n: any) => (n.id === updated.id ? { ...n, ...updated } : n))
            );
          }
        )
        .subscribe();
    } else {
      start();
    }
  }, [userId]);

  const unreadCount = notifications.filter((n: any) => !n.read).length;

  const markAsRead = async (notifId: string) => {
    await (supabase.from("notifications") as any).update({ read: true }).eq("id", notifId);
    publishNotifications(
      notificationCache.map((n: any) => (n.id === notifId ? { ...n, read: true } : n))
    );
  };

  const markAllAsRead = async () => {
    if (!userId) return;
    await (supabase.from("notifications") as any).update({ read: true }).eq("user_id", userId).eq("read", false);
    publishNotifications(notificationCache.map((n: any) => ({ ...n, read: true })));
  };

  return { notifications, unreadCount, loading, markAsRead, markAllAsRead, refresh: () => {} };
}

