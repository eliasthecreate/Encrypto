export interface PostWithDetails extends Post {
  profiles: Pick<Profile, "id" | "name" | "department" | "year" | "status" | "avatar_url">;
  like_count: number;
  comment_count: number;
  is_liked_by_me: boolean;
}

export function useFeedPosts() {
  const [posts, setPosts] = useState<PostWithDetails[]>([]);
  const [loading, setLoading] = useState(true);
  const { isAuthenticated } = useAuth();

  // Notifications are generated by database triggers so they work no matter
  // which client (web, Android, a future backend job) performed the action.
  const notify = async (
    recipientId: string,
    actorId: string,
    type: string,
    title: string,
    body: string
  ) => {
    if (!recipientId || recipientId === actorId) return;
    const { error } = await (supabase.from("notifications") as any).insert({
      user_id: recipientId,
      actor_id: actorId,
      type,
      title,
      body,
    });
    if (error) console.error("Failed to create notification:", error.message);
  };

  const fetchPosts = useCallback(async () => {
    setLoading(true);
    try {
      const { data: rawData, error } = await supabase
        .from("posts")
        .select(`
          *,
          profiles!inner(id, name, department, year, status, avatar_url)
        `)
        .order("created_at", { ascending: false });

      if (error) throw error;
      const data: any[] = rawData ?? [];

      const postsWithMeta = await Promise.all(
        data.map(async (post: any) => {
          const { count: likeCount } = await supabase
            .from("post_likes")
            .select("*", { count: "exact", head: true })
            .eq("post_id", post.id);

          const { count: commentCount } = await supabase
            .from("comments")
            .select("*", { count: "exact", head: true })
            .eq("post_id", post.id);

          let isLikedByMe = false;
          if (isAuthenticated) {
            const { data: sessionData } = await supabase.auth.getSession();
            if (sessionData?.session?.user) {
              const { data: like } = await supabase
                .from("post_likes")
                .select("id")
                .eq("post_id", post.id)
                .eq("user_id", sessionData.session.user.id)
                .maybeSingle();
              isLikedByMe = !!like;
            }
          }

          return {
            ...post,
            like_count: likeCount ?? 0,
            comment_count: commentCount ?? 0,
            is_liked_by_me: isLikedByMe,
          } as PostWithDetails;
        })
      );

      setPosts(postsWithMeta);
    } catch (err) {
      console.error("Failed to fetch posts:", err);
    } finally {
      setLoading(false);
    }
  }, [isAuthenticated]);

  useEffect(() => {
    fetchPosts();
  }, [fetchPosts]);

  const likePost = async (postId: string) => {
    const { data: sessionData } = await supabase.auth.getSession();
    if (!sessionData?.session?.user) return;
    const uid = sessionData.session.user.id;

    const existing = await supabase
      .from("post_likes")
      .select("id")
      .eq("post_id", postId)
      .eq("user_id", uid)
      .maybeSingle();

    if (existing.data) {
      await supabase.from("post_likes").delete().eq("id", (existing.data as any).id);
    } else {
      await supabase.from("post_likes").insert({ post_id: postId, user_id: uid } as any);

      // Send notification to post author
      const postRes = await (supabase.from("posts") as any).select("user_id").eq("id", postId).single();
      if (postRes.data) {
        const myProfileRes = await (supabase.from("profiles") as any).select("name").eq("id", uid).single();
        await notify(
          postRes.data.user_id,
          uid,
          "like",
          "New Like",
          `${myProfileRes.data?.name ?? "Someone"} liked your post.`
        );
      }
    }
    fetchPosts();
  };

  const addComment = async (postId: string, content: string) => {
    const { data: sessionData } = await supabase.auth.getSession();
    if (!sessionData?.session?.user) return;
    const uid = sessionData.session.user.id;
    await supabase.from("comments").insert({
      post_id: postId,
      user_id: uid,
      content,
    } as any);

    // Send notification to post author
    const postRes = await (supabase.from("posts") as any).select("user_id").eq("id", postId).single();
    if (postRes.data) {
      const myProfileRes = await (supabase.from("profiles") as any).select("name").eq("id", uid).single();
      await notify(
        postRes.data.user_id,
        uid,
        "comment",
        "New Comment",
        `${myProfileRes.data?.name ?? "Someone"} commented on your post: "${content.slice(0, 50)}${content.length > 50 ? "..." : ""}"`
      );
    }

    fetchPosts();
  };

  const createPost = async (
    content: string,
    type: "post" | "event" | "announcement" = "post",
    location?: string,
    imageUrl?: string
  ) => {
    const { data: sessionData } = await supabase.auth.getSession();
    if (!sessionData?.session?.user) return;
    const insertData: any = {
      user_id: sessionData.session.user.id,
      content,
      type,
    };
    if (location) insertData.event_location = location;
    if (imageUrl) insertData.image_url = imageUrl;
    await supabase.from("posts").insert(insertData);

    // Send notification to all friends about the new post
    if (sessionData.session.user.id) {
      // Get user's friends to notify them
      const { data: friends } = await supabase
        .from("friends")
        .select("*")
        .or(`user_id_1.eq.${sessionData.session.user.id},user_id_2.eq.${sessionData.session.user.id}`);

      const myProfileRes2 = await (supabase.from("profiles") as any).select("name").eq("id", sessionData.session.user.id).single();
      const myProfile = myProfileRes2.data;

      for (const f of (friends ?? [])) {
        const friendId = (f as any).user_id_1 === sessionData.session.user.id ? (f as any).user_id_2 : (f as any).user_id_1;
        await (supabase.from("notifications") as any).insert({
          user_id: friendId,
          actor_id: sessionData.session.user.id,
          type: "new_post",
          title: "New Post",
          body: `${myProfile?.name ?? "Someone"} just shared a new ${type}!`,
        });
      }
    }

    fetchPosts();
  };

  return { posts, loading, likePost, addComment, createPost, refresh: fetchPosts };
}

